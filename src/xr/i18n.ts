export function getLang(): Lang {
  return useXRApp.getState().settings.lang
}

/** Translate an English UI string; `{name}` placeholders are filled from `vars`. */
export function t(en: string, vars?: Record<string, string | number>, lang: Lang = getLang()): string {
  let out = lang === 'id' ? (ID[en] ?? en) : en
  if (vars) for (const [k, v] of Object.entries(vars)) out = out.split(`{${k}}`).join(String(v))
  return out
}

/** Subscribe a component to language changes; returns the bound translator. */
export function useT() {
  const lang = useXRApp((s) => s.settings.lang)
  return (en: string, vars?: Record<string, string | number>) => t(en, vars, lang)
}

type HotspotText = { title: string; short: string; detail: string }
const HOTSPOTS: Record<Lang, Record<string, HotspotText>> = { en: {}, id: idHotspots as Record<string, HotspotText> }

/** Info-pin text in the current language (falls back to the English content file). */
export function localHotspot<T extends Hotspot | null>(h: T, lang: Lang = getLang()): T {
  if (!h) return h
  const tr = HOTSPOTS[lang][h.id]
  return tr ? { ...h, ...tr } : h
}
